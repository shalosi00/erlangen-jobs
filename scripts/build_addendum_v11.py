def heading(text, style, level=0):
    key = "h_" + hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph(f'<a name="{key}"/><b>{text}</b>', style)
    p.bookmark_name = key; p.bookmark_level = level
    p.bookmark_text = text; p.bookmark_key = key
    return p

